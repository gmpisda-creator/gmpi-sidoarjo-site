import assert from 'node:assert/strict';
import fs from 'node:fs';
await import('../../card-organization.js');
const o=globalThis.GMPICardOrganization;
assert.equal(o.districts.length,18);
assert.equal(o.title('Ketua','DPC','Waru'),'Ketua DPC Waru');
assert.equal(o.title('Sekretaris DPC Waru','DPC','Candi'),'Sekretaris DPC Candi');
assert.equal(o.title('Bendahara DPC Waru','DPD',''),'Bendahara DPD');
assert.equal(o.title('Anggota','',''),'Anggota');
assert(!o.changed({}, {organization_level:null,dpc_district:null}));
assert(o.changed({organization_level:'DPC',dpc_district:'Waru'}, {organization_level:'DPC',dpc_district:'Candi'}));
const sql=fs.readFileSync('supabase/migrations/202610310044_card_organization.sql','utf8');
assert(sql.includes('new.organization_level, new.dpc_district'));
assert(sql.includes('old.organization_level, old.dpc_district'));
assert(!/update public.member_cards|card_token\s*=/.test(sql));
assert(sql.includes('dpc_district is not null'));
const js=fs.readFileSync('admin.js','utf8');
assert(js.includes('if (organizationReady)'));
assert(js.includes('organization.changed(editing,payload)'));
assert(fs.readFileSync('admin.html','utf8').includes('card-organization.js?v=1'));
console.log('PASS organization title/change helpers and static migration/approval/readiness integration. No live database execution.');
