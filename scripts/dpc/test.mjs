import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync('dpc.js','utf8');
const context={window:{},document:{getElementById:()=>null}};vm.runInNewContext(js,context);
assert.equal(context.window.GMPIDpc.districts.length,18);
assert.equal(new Set(context.window.GMPIDpc.districts).size,18);
assert.equal(typeof context.window.GMPIDpc.admin,'function');
assert(!js.includes('innerHTML'));
assert(!js.includes('member_registrations'));
assert(js.includes("published:'eq.true'"));
assert(js.includes('.range(page*100,page*100+99)'));
assert(js.includes("offset:String(page*100)"));
const sql=fs.readFileSync('supabase/migrations/202610310043_dpc_directory.sql','utf8');
assert(sql.includes('enable row level security'));
assert(sql.includes('using(published)'));
assert(sql.includes("array['owner','content_editor']"));
assert(sql.includes('published boolean not null default false'));
for(const name of context.window.GMPIDpc.districts)assert(sql.includes(`'${name}'`));
for(const file of ['index.html','admin.html'])assert(fs.readFileSync(file,'utf8').includes('dpc.js?v=1'));
console.log('PASS DPC static checks: 18 districts, draft default, RLS, role guard, pagination, text-only rendering, script wiring. Live database and browser tests not run.');
